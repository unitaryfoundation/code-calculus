#!/usr/bin/env python3
"""Generate the ingested code-state instances.

Writes `lean/CodeCalculus/IngestedInstances.lean`: for each matrix
presentation below, the block of `machine/ingestion.py` (the presentation
literal, its binding hash, the ingested state, and the kernel-checked
binding theorem), followed by a kill certificate and a minimum-weight
witness per sector with the theorems the mechanized checker yields from
them. The contract is `spec/REPRESENTATION.md` §9. This script and the
translation are untrusted, and `lake build` is the check of every theorem.

The presentations are the pinned `codes/10-2-3-b.json` entry of
qldpc-challenge (`machine/fixtures/qldpc_10_2_3_b.json`), whose rows are
independent, and a redundant presentation of the toric code on the 2 x 2
torus (`machine/fixtures/toric_2x2.json`).

    --check     compare the committed module with a fresh generation
    --verify    read the presentation literals back out of the committed
                module and compare their hashes with the fixtures
    --presentation FILE --name NAME
                print a module for one external presentation, with no
                certificates
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from machine.certificates import (  # noqa: E402
    build_sector_lower_bound_certificate,
    lean_instance_block,
)
from machine.experiments.certificate_lean_instances import (  # noqa: E402
    first_witness,
)
from machine.ingestion import (  # noqa: E402
    binding_failures,
    checks_sha256,
    lean_ingestion_block,
    lean_ingestion_module,
)

FIXTURES = ROOT / "machine" / "fixtures"
OUTPUT = ROOT / "lean" / "CodeCalculus" / "IngestedInstances.lean"

HEADER = """
# Ingested code-state instances

Generated by `machine/experiments/code_state_lean_instances.py`; do not
edit by hand. Each instance is a matrix presentation ingested under the
contract of `spec/REPRESENTATION.md` §9. `<name>_presentation` is the
presentation in canonical order and `<name>_checks_sha256` records its
binding hash. `<name>` is the ingested state, proved well-formed, and
`<name>_binds` is `presentationBinds` (`Ingestion.lean`) by kernel
`decide`: the state has qubits `0, …, n - 1`, each of its rows is a
presented row, and each presented row is a checked combination of its
rows. The `_lower_bound` and `_exact` theorems are those of
`CertificateInstances.lean`, for the ingested states.

Lean does not compute the hash. The recorded string is compared with the
hash of the literal, and with the hash of the source presentation, by
`machine/experiments/code_state_lean_instances.py --verify` and by
`machine/test_code_state_lean.py`. The generator and the certificate
producer are not trusted, and no operation contract is evidenced.
"""

ONE_OFF_HEADER = """
# Ingested code state `%s`

Generated by `machine/experiments/code_state_lean_instances.py` under the
contract of `spec/REPRESENTATION.md` §9; do not edit by hand. The binding
hash recorded here is not computed by Lean.
"""

INSTANCES = (
    ("qldpc_10_2_3_b_ingested", "qldpc_10_2_3_b.json", {"X": 3, "Z": 3}),
    ("toric_2x2_ingested", "toric_2x2.json", {"X": 2, "Z": 2}),
)


def load(filename):
    with open(FIXTURES / filename) as source:
        return json.load(source)


def generate():
    blocks = []
    for name, filename, distances in INSTANCES:
        block, state = lean_ingestion_block(name, load(filename))
        blocks.append(block)
        for sector in ("X", "Z"):
            bound = distances[sector]
            certificate = build_sector_lower_bound_certificate(
                state, sector, bound)
            blocks.append(lean_instance_block(
                name, state, certificate,
                witness=first_witness(state, sector, bound)))
    return lean_ingestion_module(HEADER, blocks)


def verify(text):
    """Binding failures of the committed module against the fixtures."""
    failures = []
    for name, filename, _ in INSTANCES:
        failures += ["%s: %s" % (name, failure)
                     for failure in binding_failures(text, name, load(filename))]
    return failures


def one_off(path, name):
    with open(path) as source:
        document = json.load(source)
    block, _ = lean_ingestion_block(name, document)
    return lean_ingestion_module(ONE_OFF_HEADER % name, [block],
                                 namespace="Ingested_%s" % name)


def main(argv):
    if "--presentation" in argv:
        path = argv[argv.index("--presentation") + 1]
        name = argv[argv.index("--name") + 1]
        sys.stdout.write(one_off(path, name))
        return 0
    if "--verify" in argv:
        failures = verify(OUTPUT.read_text())
        for failure in failures:
            print(failure)
        if not failures:
            for name, filename, _ in INSTANCES:
                print("%s %s" % (checks_sha256(load(filename)), name))
        return 1 if failures else 0
    text = generate()
    if "--check" in argv:
        if OUTPUT.read_text() != text:
            print("%s is stale; regenerate it" % OUTPUT.relative_to(ROOT))
            return 1
        return 0
    OUTPUT.write_text(text)
    print("wrote %s" % OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
