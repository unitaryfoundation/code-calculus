#!/usr/bin/env python3
"""Generate the kernel-checked certificate instances.

Writes `lean/CodeCalculus/CertificateInstances.lean`: for each state below,
a kill certificate per sector from the untrusted producer of
`machine/certificates.py`, a minimum-weight witness found by exhaustive
scan, and the two theorems the mechanized checker
(`lean/CodeCalculus/CertificateChecker.lean`) yields from them. This script
and the producer are untrusted. `lake build` is the check: each acceptance
premise is `by decide`, so the Lean kernel runs the checker.

The states are the `W3` result `A1` of `machine/fixtures/mvp_fixtures.json`
(``d_X = 2``, ``d_Z = 1``) and the pinned `codes/10-2-3-b.json` parent of
the qLDPC replay (``d_X = d_Z = 3``).

Run with ``--check`` to compare the committed file with a fresh generation.
"""

import itertools
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from machine.certificates import (  # noqa: E402
    _witness_failure,
    build_sector_lower_bound_certificate,
    lean_instance_block,
    lean_instance_module,
)
from machine.priced_calculus import CodeState, Row  # noqa: E402

FIXTURE = ROOT / "machine" / "fixtures" / "qldpc_10_2_3_b.json"
OUTPUT = ROOT / "lean" / "CodeCalculus" / "CertificateInstances.lean"

HEADER = """
# Kernel-checked certificate instances

Generated by `machine/experiments/certificate_lean_instances.py`; do not
edit by hand. Each `_lower_bound` theorem is `certificate_lower_bound_ext`
applied to a certificate the kernel accepts by `decide`, and each `_exact`
theorem adds a checked witness (`certificate_equality`). These are per-state
atomic judgments keyed to the state term, the sector distance, and the
sector (`spec/OPERATIONAL_SEMANTICS.md` §4.24). Their evidence status is
`certificate-checked` (`spec/CLAIMS.md`, *Admission*). They are statements
about the Lean terms `w3_result` and `qldpc_10_2_3_b` defined here, each
proved well-formed, and `w3_result` proved equal to `fixture_W3_result`.
The generator and the certificate producer are not trusted, and no
operation contract is evidenced.
"""


def w3_result():
    """The `W3` result state `A1` (`lean/CodeCalculus/Fixtures.lean`)."""
    return CodeState(
        (1, 2, 3),
        (Row("a2", "X", (2, 3)), Row("b1", "Z", (1, 2, 3))),
        frozenset({"a1", "a2", "b1"}))


def pinned_parent():
    with open(FIXTURE) as source:
        return CodeState.from_challenge(json.load(source))


INSTANCES = (
    ("w3_result", w3_result, {"X": 2, "Z": 1}),
    ("qldpc_10_2_3_b", pinned_parent, {"X": 3, "Z": 3}),
)


def first_witness(state, sector, weight):
    """The first weight-``weight`` sector logical in lexicographic order."""
    for support in itertools.combinations(state.Q, weight):
        if _witness_failure(state, sector, weight, support) is None:
            return support
    raise ValueError("no %s-logical of weight %d" % (sector, weight))


def generate():
    states, blocks = {}, []
    for name, build, distances in INSTANCES:
        state = build()
        states[name] = state
        for sector in ("X", "Z"):
            bound = distances[sector]
            certificate = build_sector_lower_bound_certificate(
                state, sector, bound)
            blocks.append(lean_instance_block(
                name, state, certificate,
                witness=first_witness(state, sector, bound)))
    return lean_instance_module(
        HEADER, states, blocks, same_as={"w3_result": "fixture_W3_result"})


def main(argv):
    text = generate()
    if "--check" in argv:
        if OUTPUT.read_text() != text:
            print("%s is stale; regenerate it" % OUTPUT.relative_to(ROOT))
            return 1
        return 0
    OUTPUT.write_text(text)
    print("wrote %s" % OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
