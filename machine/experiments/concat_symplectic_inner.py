#!/usr/bin/env python3
"""Concatenation of a CSS outer code with a symplectic inner code (issue #573).

Issue #573 asks whether `A-CONCAT` should accept an inner code given as a
finite symplectic matrix pair with logical representatives, under a guard
that the composite is a CSS code. This module is the evidence for that
decision. It admits nothing: `A-CONCAT` is admitted for CSS factors only
(`spec/TAXONOMY.md` section 2.14), and nothing here is a calculus rule.

A Pauli on ``n`` qubits is a pair ``(x, z)`` of bitmasks, read up to phase.
The inner code is a list of commuting Paulis on ``n_in`` qubits and, for
each of its ``k_in`` logical qubits, a pair of logical Paulis. The
composite on ``n_in`` times the number of blocks qubits is generated by the
inner stabilizers on every block and by each outer row lifted through the
logical Paulis, an X-row through the first of each pair and a Z-row through
the second.

* `symplectic_concatenate` builds those generators.
* `css_split` decides whether a group of Paulis is CSS, meaning that it is
  generated by its elements with ``z = 0`` and its elements with ``x = 0``.
  This is the guard the issue calls a decidable CSS-composite check.
* `css_composite_state` returns the composite as a `CodeState` when the
  guard holds and raises `NoDerivation` when it does not.
* `block_groups` computes, for each block, the group of composite elements
  supported on that block: the inner stabilizers and the lifts of the
  outer stabilizers confined to the block. If the composite is CSS then
  each of these groups is CSS
  (`design/A_CONCAT_SYMPLECTIC_INNER_PROPOSAL.md`, section 3; the note is
  in the development repository only).

Run as a script to print the guard's verdict on the two inner codes the
issue names.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from machine.constructors import _constructed_state  # noqa: E402
from machine.priced_calculus import (  # noqa: E402
    CodeState,
    Malformed,
    NoDerivation,
    Row,
)

# Stabilizer generators of the two non-CSS inner codes of the board entries
# `codes/512-54-24.json`, `codes/576-42-24.json` (inner `[[8,3,3]]`) and
# `codes/672-28-30.json` (inner `[[8,2,3]]`) of qldpc-challenge, as
# (X support, Z support) pairs, from `codes/8-3-3.json` and
# `codes/8-2-3.json` there.
INNER_8_3_3 = (
    ((0, 4, 6, 7), (2, 4, 5, 7)),
    ((3, 5, 6, 7), (0, 2, 5, 6)),
    ((1, 4, 5, 6), (2, 3, 4, 6)),
    ((3, 5, 6, 7), (1, 3, 4, 7)),
    ((2, 3, 4, 6), (3, 5, 6, 7)),
)
INNER_8_2_3 = (
    ((5, 7), (0, 5, 6, 7)),
    ((4, 6), (3, 7)),
    ((3, 4), (0, 1, 3, 4)),
    ((2, 5), (1, 7)),
    ((1,), (2, 4, 6)),
    ((0,), (2, 3, 5)),
)


def mask(support):
    value = 0
    for q in support:
        value |= 1 << q
    return value


def pauli(x_support=(), z_support=()):
    return (mask(x_support), mask(z_support))


def commute(a, b):
    """Whether two Paulis commute: the symplectic product is 0."""
    return ((a[0] & b[1]).bit_count() + (a[1] & b[0]).bit_count()) % 2 == 0


def _combined(p, n):
    return p[0] | (p[1] << n)


def _rank(vectors):
    basis = {}
    for value in vectors:
        while value:
            pivot = value.bit_length() - 1
            if pivot in basis:
                value ^= basis[pivot]
            else:
                basis[pivot] = value
                break
    return len(basis)


def _restricted_span(vectors, allowed):
    """A spanning set of the vectors of the span that vanish outside
    ``allowed``."""
    pivots = {}
    inside = []
    for value in vectors:
        while value & ~allowed:
            pivot = (value & ~allowed).bit_length() - 1
            if pivot in pivots:
                value ^= pivots[pivot]
            else:
                pivots[pivot] = value
                value = 0
        if value:
            inside.append(value)
    return inside


def css_split(n, paulis):
    """``(rank, x_part, z_part)`` for the group ``paulis`` generate.

    ``x_part`` spans the elements with no Z component, as X masks, and
    ``z_part`` the elements with no X component, as Z masks. The group is
    CSS exactly when ``len(basis of x_part) + len(basis of z_part)`` equals
    ``rank``; `is_css_group` tests that.
    """
    combined = [_combined(p, n) for p in paulis]
    low = (1 << n) - 1
    x_part = _restricted_span(combined, low)
    z_part = [value >> n for value in _restricted_span(combined, low << n)]
    return _rank(combined), x_part, z_part


def is_css_group(n, paulis):
    rank, x_part, z_part = css_split(n, paulis)
    return _rank(x_part) + _rank(z_part) == rank


def check_inner(n_in, stabilizers, logicals):
    """Validate the inner input; returns ``k_in``.

    The stabilizers commute and are independent, each logical commutes with
    every stabilizer, and the logical pairs form a symplectic basis: the
    two members of a pair anticommute and all other pairs of logicals
    commute. ``n_in`` minus the number of stabilizers must be the number of
    pairs.
    """
    full = (1 << n_in) - 1
    everything = list(stabilizers) + [p for pair in logicals for p in pair]
    for p in everything:
        if (not isinstance(p, tuple) or len(p) != 2
                or any(not isinstance(m, int) or isinstance(m, bool)
                       or m < 0 or m & ~full for m in p)):
            raise Malformed("an inner Pauli is not a pair of masks over "
                            "n_in qubits")
    for i, a in enumerate(stabilizers):
        for b in stabilizers[i + 1:]:
            if not commute(a, b):
                raise Malformed("inner stabilizers do not commute")
    if _rank([_combined(p, n_in) for p in stabilizers]) != len(stabilizers):
        raise Malformed("inner stabilizers are dependent")
    if n_in - len(stabilizers) != len(logicals):
        raise Malformed("inner logical pairs must number n_in minus the "
                        "number of stabilizers")
    flat = [(j, side, p) for j, pair in enumerate(logicals)
            for side, p in enumerate(pair)]
    for _, _, p in flat:
        if not all(commute(p, s) for s in stabilizers):
            raise Malformed("an inner logical does not commute with the "
                            "inner stabilizers")
    for a_index, (ja, sa, pa) in enumerate(flat):
        for jb, sb, pb in flat[a_index + 1:]:
            if commute(pa, pb) == (ja == jb and sa != sb):
                raise Malformed("inner logicals are not a symplectic basis")
    return len(logicals)


def symplectic_logical_basis(n_in, stabilizers):
    """A symplectic basis of logical Paulis for a stabilizer group.

    A list of ``n_in - len(stabilizers)`` pairs. The choice is the first
    one a fixed elimination order finds, and no weight is minimized.
    """
    candidates = []
    for index in range(2 * n_in):
        p = (1 << index, 0) if index < n_in else (0, 1 << (index - n_in))
        candidates.append(p)
    # Reduce the unit Paulis to a spanning set of the normalizer: for each
    # stabilizer, drop one Pauli that anticommutes with it and add it to
    # every other Pauli that does.
    for s in stabilizers:
        partner = next(c for c in candidates if not commute(c, s))
        candidates = [c if commute(c, s) else
                      (c[0] ^ partner[0], c[1] ^ partner[1])
                      for c in candidates if c != partner]
    pairs = []
    pool = list(candidates)
    stabilizer_span = [_combined(s, n_in) for s in stabilizers]
    while pool:
        first = pool.pop(0)
        if _rank(stabilizer_span + [_combined(first, n_in)]) == len(stabilizers):
            continue
        partner = next((c for c in pool if not commute(c, first)), None)
        if partner is None:
            continue
        pool.remove(partner)
        updated = []
        for c in pool:
            if not commute(c, first):
                c = (c[0] ^ partner[0], c[1] ^ partner[1])
            if not commute(c, partner):
                c = (c[0] ^ first[0], c[1] ^ first[1])
            updated.append(c)
        pool = updated
        pairs.append((first, partner))
    return pairs


def _groups(outer, groups, k_in):
    groups = [tuple(group) for group in groups]
    labels = [label for group in groups for label in group]
    if (any(len(group) != k_in for group in groups)
            or sorted(labels) != sorted(outer.Q)
            or len(set(labels)) != len(labels)):
        raise Malformed("blocks must partition the outer qubits into "
                        "k_in-tuples")
    return groups


def _lift(row_mask, sector, groups, logicals, n_in):
    x = z = 0
    for block, group in enumerate(groups):
        for position, label in enumerate(group):
            if (row_mask >> label) & 1:
                lx, lz = logicals[position][0 if sector == "X" else 1]
                x ^= lx << (block * n_in)
                z ^= lz << (block * n_in)
    return (x, z)


def symplectic_concatenate(outer, n_in, stabilizers, logicals, groups):
    """The generators of the composite, as Paulis on ``n_in * blocks``
    qubits: the inner stabilizers on every block, then the lifted outer
    rows in display order. Returns ``(n, generators)``."""
    if not isinstance(outer, CodeState):
        raise Malformed("the outer code must be a CodeState")
    k_in = check_inner(n_in, list(stabilizers), list(logicals))
    if k_in == 0:
        raise NoDerivation("the inner code encodes no qubit")
    groups = _groups(outer, groups, k_in)
    generators = []
    for block in range(len(groups)):
        shift = block * n_in
        generators += [(x << shift, z << shift) for x, z in stabilizers]
    for row in outer.rows:
        generators.append(_lift(row.mask, row.sector, groups, logicals, n_in))
    return n_in * len(groups), generators


def block_groups(outer, n_in, stabilizers, logicals, groups):
    """For each block, generators of the composite elements supported on
    it, as Paulis on ``n_in`` qubits: the inner stabilizers and the lifts
    of the outer stabilizers confined to the block's outer qubits."""
    k_in = check_inner(n_in, list(stabilizers), list(logicals))
    groups = _groups(outer, groups, k_in)
    result = []
    for group in groups:
        allowed = mask(group)
        confined = []
        for sector in ("X", "Z"):
            rows = [row.mask for row in outer.sector_rows(sector)]
            for value in _restricted_span(rows, allowed):
                confined.append(_lift(value, sector, [group], logicals, n_in))
        result.append(list(stabilizers) + confined)
    return result


def css_composite_state(outer, n_in, stabilizers, logicals, groups):
    """The composite as a `CodeState`, when its stabilizer group is CSS.

    Raises `NoDerivation` when the group is not CSS. The returned display
    is a basis of the X-type elements and a basis of the Z-type elements,
    with canonically minted identifiers.
    """
    n, generators = symplectic_concatenate(
        outer, n_in, stabilizers, logicals, groups)
    rank, x_part, z_part = css_split(n, generators)
    x_rank, z_rank = _rank(x_part), _rank(z_part)
    if x_rank + z_rank != rank:
        raise NoDerivation(
            "the composite stabilizer group is not CSS: rank %d, X-type "
            "elements of dimension %d, Z-type elements of dimension %d"
            % (rank, x_rank, z_rank))
    rows = [("X", value) for value in x_part] + [("Z", value) for value in z_part]
    state, _ = _constructed_state(n, rows)
    return state


def _small_outer(n):
    """The CSS state on ``n`` qubits (``n`` even) with one all-qubit row
    per sector."""
    support = tuple(range(n))
    return CodeState(support, (Row("a1", "X", support), Row("b1", "Z", support)),
                     frozenset({"a1", "b1"}))


def main():
    for name, inner, outer, groups in (
            ("[[8,3,3]] inner, [[6,4,2]] outer", INNER_8_3_3, _small_outer(6),
             [(0, 1, 2), (3, 4, 5)]),
            ("[[8,2,3]] inner, [[4,2,2]] outer", INNER_8_2_3, _small_outer(4),
             [(0, 1), (2, 3)])):
        stabilizers = [pauli(x, z) for x, z in inner]
        logicals = symplectic_logical_basis(8, stabilizers)
        n, generators = symplectic_concatenate(outer, 8, stabilizers,
                                               logicals, groups)
        rank, x_part, z_part = css_split(n, generators)
        print("%s: n=%d rank=%d X-type=%d Z-type=%d CSS=%s" % (
            name, n, rank, _rank(x_part), _rank(z_part),
            is_css_group(n, generators)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
