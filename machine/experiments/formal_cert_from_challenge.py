#!/usr/bin/env python3
"""End-to-end formal-certificate generator for a challenge entry (issue #645).

    python3 machine/experiments/formal_cert_from_challenge.py ENTRY.json \\
        --name NAME [--sector X --bound B]... [--repo URL] [--commit REV]
        [--well-formedness auto|always|never] [--allow-large] [--no-build]

Reads a qldpc-challenge entry (``codes/<slug>.json``), ingests it
(`machine/ingestion.py`), builds a pruning-tree certificate per sector
(`build_sector_lower_bound_tree_certificate`), and writes the Lean module
``lean/CodeCalculus/FormalCerts/<NAME>.lean``: the ingestion block, one
tree block per sector, and the theorem ``<NAME>_certified`` that conjoins
the binding theorem with each sector's bound. It then checks the module's
binding hash against the entry (`binding_failures`), runs
``lake build CodeCalculus.FormalCerts.<NAME>``, checks that
``<NAME>_certified`` depends on no axiom outside ``propext``,
``Classical.choice`` and ``Quot.sound``, and prints the ``certs/<slug>.json``
payload (`machine.certificates.export_challenge_certificate`) on stdout.
Progress goes to stderr.

``--sector`` and ``--bound`` pair up and may repeat; with no ``--sector``
both sectors are certified, and with no ``--bound`` each sector's bound is
the entry's witnessed value for it. A sector's witness is read from the
entry; when its weight equals the bound the module also proves the sector
exact. The payload is exact when the least bound is the entry's ``d``,
and partial otherwise. A run with one sector writes and builds the module
but prints no payload: the board does not accept a bound on one side.

The payload names a commit, so it is printed only when the module at that
commit (``--commit``, default ``HEAD``) is the one just generated: commit
the module, then run again. ``--repo`` is required for a payload, since
only the caller knows where the commit is published. The toolchain is
read from ``lean/lean-toolchain`` at that commit.

``--well-formedness auto`` (the default) leaves ``<NAME>_wellFormed`` out
above ``LEAN_WELL_FORMEDNESS_ROW_LIMIT`` retained rows per sector; the
certified theorem does not use it. Entries above
``LEAN_GENERATION_QUBIT_LIMIT`` qubits are refused unless
``--allow-large``. Both limits are in `machine/ingestion.py`, and the
measurements behind them in `machine/experiments/benchmark_formal_cert.py`.

Exit status: 0 on success (with or without a payload), 1 when the input
or a certificate is refused, 2 when the Lean build or the axiom check
fails, 3 when the module is not committed at the named commit.
"""

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from machine.certificates import (  # noqa: E402
    NoCertificate,
    build_sector_lower_bound_tree_certificate,
    export_challenge_certificate,
    lean_tree_instance_block,
)
from machine.ingestion import (  # noqa: E402
    LEAN_GENERATION_QUBIT_LIMIT,
    LEAN_NAME,
    SECTORS,
    binding_failures,
    ingest,
    lean_certified_block,
    lean_ingestion_block,
    lean_ingestion_module,
    retained_rows,
    well_formedness_feasible,
)
from machine.priced_calculus import Malformed  # noqa: E402

LEAN_DIR = ROOT / "lean"
MODULE_DIR = LEAN_DIR / "CodeCalculus" / "FormalCerts"
MODULE_PREFIX = "CodeCalculus.FormalCerts"
GENERATED_MARK = "Generated by machine/experiments/formal_cert_from_challenge.py"
STANDARD_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}


class Refused(Exception):
    """An input, certificate or check the generator will not go past."""

    def __init__(self, message, status=1):
        super().__init__(message)
        self.status = status


def log(message):
    print(message, file=sys.stderr)


def module_path(name):
    return MODULE_DIR / ("%s.lean" % name)


def module_name(name):
    return "%s.%s" % (MODULE_PREFIX, name)


def theorem_name(name):
    return "CodeCalculus.FormalCert_%s.%s_certified" % (name, name)


def build_command(name):
    return "cd lean && lake build %s" % module_name(name)


def _sector_bounds(document, sectors, bounds):
    """The sectors to certify and their bounds, from the flags and the entry."""
    sectors = [sector.upper() for sector in sectors] or list(SECTORS)
    for sector in sectors:
        if sector not in SECTORS:
            raise Refused("--sector must be X or Z, not %r" % sector)
    if len(set(sectors)) != len(sectors):
        raise Refused("a sector is named twice")
    if bounds:
        if len(bounds) != len(sectors):
            raise Refused("give one --bound per --sector")
        return dict(zip(sectors, bounds))
    distance = document.get("distance") or {}
    out = {}
    for sector in sectors:
        value = (distance.get(sector) or {}).get("value")
        if not isinstance(value, int) or isinstance(value, bool):
            raise Refused("no --bound for %s and the entry records no %s "
                          "value" % (sector, sector))
        out[sector] = value
    return out


def _entry_witnesses(document):
    distance = document.get("distance") or {}
    out = {}
    for sector in SECTORS:
        support = (distance.get(sector) or {}).get("witness")
        if support:
            out[sector] = list(support)
    return out


def generate(document, name, bounds, *, well_formedness="auto",
             allow_large=False, source="the entry"):
    """The module text and what the payload needs, or `Refused`.

    Returns a dict with ``module``, ``state``, ``certificates``,
    ``witnesses`` (the entry's), ``exact`` (the sectors proved exact) and
    ``well_formedness`` (whether ``<name>_wellFormed`` is emitted).
    """
    if not LEAN_NAME.match(name):
        raise Refused("--name must match %s" % LEAN_NAME.pattern)
    n = document.get("n")
    if (isinstance(n, int) and n > LEAN_GENERATION_QUBIT_LIMIT
            and not allow_large):
        raise Refused("n = %d is above LEAN_GENERATION_QUBIT_LIMIT = %d; "
                      "pass --allow-large to generate anyway" % (
                          n, LEAN_GENERATION_QUBIT_LIMIT))
    try:
        state = ingest(document)
    except Malformed as exc:
        raise Refused("ingestion refused the entry: %s" % exc)
    if well_formedness == "auto":
        include = well_formedness_feasible(state)
        if not include:
            log("leaving out %s_wellFormed: %d retained rows in a sector is "
                "above the limit; the certified theorem does not use it"
                % (name, retained_rows(state)))
    else:
        include = well_formedness == "always"
    block, state = lean_ingestion_block(name, document,
                                        include_well_formedness=include)
    blocks = [block]
    entry_witnesses = _entry_witnesses(document)
    certificates, exact = {}, set()
    for sector in SECTORS:
        if sector not in bounds:
            continue
        bound = bounds[sector]
        if not isinstance(bound, int) or isinstance(bound, bool) or bound < 1:
            raise Refused("the %s bound must be a positive integer" % sector)
        try:
            certificate = build_sector_lower_bound_tree_certificate(
                state, sector, bound)
        except NoCertificate as exc:
            raise Refused("no %s certificate for bound %d: %s"
                          % (sector, bound, exc))
        certificates[sector] = certificate
        witness = entry_witnesses.get(sector)
        if witness is not None and len(witness) == bound:
            exact.add(sector)
        else:
            witness = None
        try:
            blocks.append(lean_tree_instance_block(name, state, certificate,
                                                   witness=witness))
        except ValueError as exc:
            raise Refused("the %s block: %s" % (sector, exc))
    blocks.append(lean_certified_block(name, bounds, exact))
    header = ("%s from %s; do not edit by hand. `%s_certified` is the "
              "theorem a challenge certificate names." % (
                  GENERATED_MARK, source, name))
    module = lean_ingestion_module(header, blocks,
                                   namespace="FormalCert_%s" % name)
    failures = binding_failures(module, name, document)
    if failures:
        raise Refused("the module does not bind the entry: %s"
                      % "; ".join(failures))
    return {"module": module, "state": state, "certificates": certificates,
            "witnesses": entry_witnesses, "exact": exact,
            "well_formedness": include}


def write_module(name, text):
    path = module_path(name)
    if path.exists() and GENERATED_MARK not in path.read_text():
        raise Refused("%s exists and was not generated here; not "
                      "overwriting it" % path.relative_to(ROOT))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


def lake_build(name):
    command = ["lake", "build", module_name(name)]
    log("running: (cd lean && %s)" % " ".join(command))
    proc = subprocess.run(command, cwd=str(LEAN_DIR), stdout=sys.stderr,
                          stderr=sys.stderr)
    if proc.returncode != 0:
        raise Refused("lake build failed with exit %d" % proc.returncode, 2)


_AXIOMS = re.compile(r"depends on axioms: \[(?P<axioms>[^\]]*)\]")


def theorem_axioms(name):
    """The axioms ``<name>_certified`` depends on, from ``#print axioms``."""
    source = "import %s\n#print axioms %s\n" % (module_name(name),
                                                  theorem_name(name))
    with tempfile.TemporaryDirectory() as scratch:
        probe = Path(scratch) / "Axioms.lean"
        probe.write_text(source)
        proc = subprocess.run(["lake", "env", "lean", str(probe)],
                              cwd=str(LEAN_DIR), capture_output=True,
                              text=True)
    output = proc.stdout + proc.stderr
    if proc.returncode != 0:
        raise Refused("the axiom check failed:\n%s" % output.strip(), 2)
    if "does not depend on any axioms" in output:
        return []
    match = _AXIOMS.search(output)
    if match is None:
        raise Refused("could not read the axiom check:\n%s" % output.strip(),
                      2)
    return sorted(a.strip() for a in match.group("axioms").split(",")
                  if a.strip())


def _git(*args):
    return subprocess.run(["git", *args], cwd=str(ROOT), capture_output=True,
                          text=True)


def pinned_commit(name, text, revision):
    """The commit ``revision`` names, if it holds exactly this module."""
    proc = _git("rev-parse", "--verify", "%s^{commit}" % revision)
    if proc.returncode != 0:
        raise Refused("%r is not a commit here" % revision, 3)
    commit = proc.stdout.strip()
    relative = module_path(name).relative_to(ROOT).as_posix()
    shown = _git("show", "%s:%s" % (commit, relative))
    if shown.returncode != 0 or shown.stdout != text:
        raise Refused("%s at %s is not the module just generated; commit it "
                      "and run again (with --commit if it is not HEAD) to "
                      "get a payload whose commit holds the theorem"
                      % (relative, commit[:12]), 3)
    return commit


def toolchain_at(commit):
    proc = _git("show", "%s:lean/lean-toolchain" % commit)
    if proc.returncode != 0 or not proc.stdout.strip():
        raise Refused("no lean/lean-toolchain at %s" % commit[:12], 3)
    return proc.stdout.strip()


def checker_string(toolchain, axioms):
    version = toolchain.rsplit(":", 1)[-1].lstrip("v")
    used = ", ".join(axioms) if axioms else "none"
    return ("Lean %s (core library, no Mathlib); kernel-checked by lake "
            "build; axioms: %s" % (version, used))


def _parse_args(argv):
    parser = argparse.ArgumentParser(
        description=__doc__.strip().splitlines()[0])
    parser.add_argument("entry", help="a challenge entry, codes/<slug>.json")
    parser.add_argument("--name", required=True,
                        help="Lean name for the state, [a-z][a-z0-9_]*")
    parser.add_argument("--sector", action="append", default=[],
                        help="sector to certify (repeatable; default X and Z)")
    parser.add_argument("--bound", action="append", type=int, default=[],
                        help="the bound for the matching --sector (default "
                             "the entry's witnessed value)")
    parser.add_argument("--repo", default=None,
                        help="where --commit is published; required for a "
                             "payload")
    parser.add_argument("--commit", default="HEAD",
                        help="the commit holding the module (default HEAD)")
    parser.add_argument("--well-formedness", default="auto",
                        choices=("auto", "always", "never"),
                        help="emit <NAME>_wellFormed (default: by size)")
    parser.add_argument("--allow-large", action="store_true",
                        help="generate above LEAN_GENERATION_QUBIT_LIMIT")
    parser.add_argument("--no-build", action="store_true",
                        help="write the module only; no build, no payload")
    return parser.parse_args(argv)


def run(args):
    entry = Path(args.entry)
    try:
        document = json.loads(entry.read_text())
    except (OSError, ValueError) as exc:
        raise Refused("cannot read %s: %s" % (entry, exc))
    if not isinstance(document, dict):
        raise Refused("%s is not a JSON object" % entry)
    bounds = _sector_bounds(document, args.sector, args.bound)
    generated = generate(document, args.name, bounds,
                         well_formedness=args.well_formedness,
                         allow_large=args.allow_large,
                         source="`%s`" % entry.name)
    path = write_module(args.name, generated["module"])
    log("wrote %s" % path.relative_to(ROOT))
    if args.no_build:
        log("--no-build: no build, so no payload")
        return None
    lake_build(args.name)
    axioms = theorem_axioms(args.name)
    extra = sorted(set(axioms) - STANDARD_AXIOMS)
    if extra:
        raise Refused("%s depends on %s" % (theorem_name(args.name),
                                            ", ".join(extra)), 2)
    log("%s builds; axioms: %s" % (theorem_name(args.name),
                                   ", ".join(axioms) or "none"))
    if set(bounds) != set(SECTORS):
        log("one sector certified: the board takes no single-side bound, so "
            "no payload is printed")
        return None
    if args.repo is None:
        log("no --repo: the payload needs the published repository of the "
            "commit, so none is printed")
        return None
    commit = pinned_commit(args.name, generated["module"], args.commit)
    toolchain = toolchain_at(commit)
    distance = document.get("distance") or {}
    d = distance.get("d")
    witnesses = {side: support
                 for side, support in generated["witnesses"].items()}
    try:
        return export_challenge_certificate(
            document, generated["state"], generated["certificates"],
            d=d, d_exact=isinstance(d, int) and min(bounds.values()) == d,
            solver="code-calculus pruning-tree certificate, Lean kernel",
            checker=checker_string(toolchain, axioms),
            replay={"repo": args.repo, "commit": commit,
                    "theorem": theorem_name(args.name),
                    "build": build_command(args.name),
                    "toolchain": toolchain},
            witnesses=witnesses, name=document.get("name"))
    except ValueError as exc:
        raise Refused("the payload is refused: %s" % exc)


def main(argv):
    args = _parse_args(argv)
    try:
        payload = run(args)
    except Refused as exc:
        log("refused: %s" % exc)
        return exc.status
    if payload is not None:
        print(json.dumps(payload, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
